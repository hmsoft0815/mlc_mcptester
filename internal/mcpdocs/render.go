package mcpdocs

import (
	"cmp"
	"fmt"
	"strings"
)

// writer builds the document and keeps the heading anchors unique, as
// GitHub does when two headings have the same text.
type writer struct {
	b       strings.Builder
	anchors map[string]int
}

func (w *writer) p(format string, a ...any) { fmt.Fprintf(&w.b, format, a...) }

// heading writes a heading and returns its anchor.
func (w *writer) heading(level int, text string) string {
	w.p("%s %s\n\n", strings.Repeat("#", level), text)
	slug := anchor(text)
	n := w.anchors[slug]
	w.anchors[slug]++
	if n > 0 {
		slug = fmt.Sprintf("%s-%d", slug, n)
	}
	return slug
}

// Render writes the reference. The text holds no date or version, so it
// changes only when what the server offers changes — which keeps --check
// meaningful.
func Render(srv *Server) (string, error) {
	w := &writer{anchors: map[string]int{}}
	w.heading(1, cell(srv.Name)+" — MCP reference")
	w.p("> Generated by `mcp-tester docs` — do not edit by hand. Descriptions and parameters appear\n")
	w.p("> verbatim as an MCP client receives them from `tools/list` and `prompts/list`.\n\n")

	if srv.HasTools {
		if err := w.tools(srv.Tools); err != nil {
			return "", err
		}
	}
	if srv.HasPrompts {
		w.prompts(srv.Prompts)
	}
	if srv.HasResources {
		w.resources(srv.Resources, srv.Templates)
	}
	w.instructions(srv.Instructions)
	return strings.TrimRight(w.b.String(), "\n") + "\n", nil
}

func (w *writer) tools(tools []Tool) error {
	if len(tools) == 0 {
		w.heading(2, "Tools")
		w.p("The server declares tools but lists none.\n\n")
		return nil
	}
	// The overview links to anchors that exist only once the sections are
	// written, so the sections go into their own writer first.
	sections := &writer{anchors: w.anchors}
	w.anchors["overview"]++
	w.anchors["tools"]++
	links := make([]string, len(tools))
	for i, t := range tools {
		links[i] = sections.heading(3, cell(t.Name))
		if err := sections.tool(t); err != nil {
			return fmt.Errorf("tool %s: %w", t.Name, err)
		}
	}

	w.p("## Overview\n\n| Tool | Title | Result | Hints |\n|---|---|---|---|\n")
	for i, t := range tools {
		w.p("| [%s](#%s) | %s | %s | %s |\n", code(t.Name), links[i], cell(t.title()), t.resultKind(), cmp.Or(t.hints(), "—"))
	}
	w.p("\n**structured**: the tool declares an `outputSchema` and returns `structuredContent`. ")
	w.p("**text**: free-form content without a schema.\n\n")
	w.p("## Tools\n\n")
	w.b.WriteString(sections.b.String())
	return nil
}

func (t Tool) title() string {
	if t.Title == "" && t.Annotations != nil {
		return t.Annotations.Title
	}
	return t.Title
}

func (t Tool) resultKind() string {
	if len(t.OutputSchema) > 0 && string(t.OutputSchema) != "null" {
		return "structured"
	}
	return "text"
}

// hints lists the annotations the server declares as true; defaults that are
// only implied are left out, so the column shows what the server says.
func (t Tool) hints() string {
	a := t.Annotations
	if a == nil {
		return ""
	}
	var out []string
	for _, h := range []struct {
		v    *bool
		text string
	}{{a.ReadOnlyHint, "read-only"}, {a.DestructiveHint, "destructive"}, {a.IdempotentHint, "idempotent"}, {a.OpenWorldHint, "open-world"}} {
		if h.v != nil && *h.v {
			out = append(out, h.text)
		}
	}
	return strings.Join(out, ", ")
}

func (w *writer) tool(t Tool) error {
	if title := t.title(); title != "" {
		w.p("**%s**\n\n", cell(title))
	}
	if d := strings.TrimSpace(t.Description); d != "" {
		w.p("%s\n\n", d)
	}
	if err := w.parameters(t.InputSchema); err != nil {
		return err
	}
	return w.resultFields(t.OutputSchema)
}

func (w *writer) parameters(raw []byte) error {
	in, err := parseSchema(raw)
	if err != nil {
		return err
	}
	props, err := in.properties()
	if err != nil {
		return err
	}
	if len(props) == 0 {
		w.p("No parameters.\n\n")
		return nil
	}
	w.p("| Parameter | Type | Required | Description |\n|---|---|---|---|\n")
	for _, p := range props {
		w.p("| %s | %s | %s | %s |\n", code(p.Name), cell(p.Schema.typeText()), yes(p.Required), cell(p.Schema.Description))
	}
	w.p("\n")
	return nil
}

// resultFields names the fields of the output schema, one level deep:
// `matches` (kind, id, label).
func (w *writer) resultFields(raw []byte) error {
	out, err := parseSchema(raw)
	if err != nil {
		return err
	}
	props, err := out.properties()
	if err != nil {
		return err
	}
	if len(props) == 0 {
		if len(raw) > 0 && string(raw) != "null" {
			w.p("Result (`structuredContent`): %s.\n\n", cell(out.baseType()))
			return nil
		}
		w.p("Result: text.\n\n")
		return nil
	}
	fields := make([]string, len(props))
	for i, p := range props {
		fields[i] = code(p.Name)
		if sub := p.Schema.nestedNames(); len(sub) > 0 {
			fields[i] += " (" + cell(strings.Join(sub, ", ")) + ")"
		}
	}
	w.p("Result (`structuredContent`): %s\n\n", strings.Join(fields, ", "))
	return nil
}

// nestedNames are the property names of an object, or of the items of an
// array of objects.
func (s schema) nestedNames() []string {
	props, _ := s.properties()
	if len(props) == 0 {
		items, err := parseSchema(s.Items)
		if err != nil {
			return nil
		}
		props, _ = items.properties()
	}
	names := make([]string, len(props))
	for i, p := range props {
		names[i] = p.Name
	}
	return names
}
